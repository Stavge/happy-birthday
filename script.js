function advanceCurrentExperience() {

  if (interactionLocked) {
    return;
  }


  if (
    isInteractiveStoryScreen()
  ) {

    revealNextStoryLine();

  }


  else if (
    isInteractivePoemScreen()
  ) {

    revealNextPoemStanza();

  }

}


