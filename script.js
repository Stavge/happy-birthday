function resetStory() {

  storySceneIndex = 0;

  storyLineIndex = 0;

  storyLines.innerHTML = "";

  storyScreen.className =
    "screen theme-opening hidden";

  progressTotal.textContent =
    String(storyScenes.length)
      .padStart(2, "0");

}


/* =========================================
   STORY
========================================= */

function renderStoryScene() {

  const scene =
    storyScenes[storySceneIndex];

  storyScreen.className =
    `screen theme-${scene.theme}`;

  storyKicker.textContent =
    scene.kicker;

  storyLines.innerHTML = "";

  storyLineIndex = 0;

  progressNumber.textContent =
    String(storySceneIndex + 1)
      .padStart(2, "0");

  progressTotal.textContent =
    String(storyScenes.length)
      .padStart(2, "0");

  storyContainer
    .classList
    .remove("scene-enter");

  void storyContainer.offsetWidth;

  storyContainer
    .classList
    .add("scene-enter");

}


function revealNextStoryLine() {

  if (interactionLocked) {
    return;
  }

  const scene =
    storyScenes[storySceneIndex];

  if (
    storyLineIndex <
    scene.lines.length
  ) {

    const lineData =
      getStoryLineData(
        scene.lines[storyLineIndex]
      );

    const line =
      document.createElement("p");

    line.className =
      "story-line";

    line.textContent =
      lineData.text;

    applyStoryLineStyle(
      line,
      lineData.style
    );


    if (
      scene.theme === "hope" &&
      storyLineIndex ===
      scene.lines.length - 1
    ) {

      line.classList.add(
        "story-line-emphasis"
      );

    }


    storyLines.appendChild(line);


    requestAnimationFrame(() => {

      line.classList.add("visible");

    });


    storyLineIndex += 1;

    keepNewestStoryLineVisible();

    return;

  }


  if (
    storySceneIndex <
    storyScenes.length - 1
  ) {

    goToNextStoryScene();

    return;

  }


  startPoem();

}


function goToNextStoryScene() {

  interactionLocked = true;

  storyContainer
    .classList
    .add("scene-leave");


  setTimeout(() => {

    storySceneIndex += 1;

    renderStoryScene();

    storyContainer
      .classList
      .remove("scene-leave");


    setTimeout(() => {

      interactionLocked = false;

      revealNextStoryLine();

    }, 180);

  }, 520);

}


function keepNewestStoryLineVisible() {

  const newest =
    storyLines.lastElementChild;

  if (!newest) {
    return;
  }

  newest.scrollIntoView({
    behavior: "smooth",
    block: "nearest"
  });

}


/* =========================================
   POEM
========================================= */

function startPoem() {

  if (interactionLocked) {
    return;
  }

  interactionLocked = true;

  poemIndex = 0;

  poemLines.innerHTML = "";


  changeScreen(
    storyScreen,
    poemScreen,
    720
  );


  setTimeout(() => {

    interactionLocked = false;

    revealNextPoemStanza();

  }, 850);

}


function revealNextPoemStanza() {

  if (interactionLocked) {
    return;
  }


  if (
    poemIndex <
    poemStanzas.length
  ) {

    const stanza =
      document.createElement("div");

    stanza.className =
      "poem-stanza";


    poemStanzas[poemIndex]
      .forEach((text) => {

        const line =
          document.createElement("p");

        line.textContent =
          text;

        stanza.appendChild(line);

      });


    poemLines.appendChild(stanza);


    requestAnimationFrame(() => {

      stanza.classList.add("visible");

    });


    poemIndex += 1;


    stanza.scrollIntoView({
      behavior: "smooth",
      block: "nearest"
    });


    return;

  }


  changeScreen(
    poemScreen,
    musicScreen,
    720
  );

}


